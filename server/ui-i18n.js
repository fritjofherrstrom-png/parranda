function normalizeLanguage(value) {
  const lang = String(value || "").trim().toLowerCase().split("-")[0];
  return supportedLanguages.includes(lang) ? lang : fallbackLanguage;
}

function formatText(template, replacements = {}) {
  return Object.entries(replacements).reduce(
    (text, [token, value]) => text.split(`{${token}}`).join(String(value)),
    String(template || ""),
  );
}

function translate(language, key, replacements = {}, fallback = "") {
  const lang = normalizeLanguage(language);
  const template =
    translations[lang]?.[key] ??
    translations[fallbackLanguage]?.[key] ??
    fallback ??
    key;

  return formatText(template, replacements);
}

function buildClientI18nPayload() {
  return {
    fallbackLanguage,
    supportedLanguages,
    translations,
  };
}

