function normalizeLookup(value) {
  return String(value || "")
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .trim();
}

function findItemByName(name) {
  return normalizedItemsByName.get(normalizeLookup(name)) || null;
}

